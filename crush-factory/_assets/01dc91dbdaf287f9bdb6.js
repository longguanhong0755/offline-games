var _currentLang = 'en';

function _matKey(name) {
    return name.charAt(0).toLowerCase() + name.slice(1).replace(/\s+(\w)/g, function(_, c) { return c.toUpperCase(); });
}

function t(key, vars) {
    var val = (I18N[_currentLang] && I18N[_currentLang][key]);
    if (val === undefined) val = I18N.en[key];
    if (val === undefined && key.endsWith('.gen')) {
        var base = key.slice(0, -4);
        val = (I18N[_currentLang] && I18N[_currentLang][base]) || I18N.en[base];
    }
    if (val === undefined) val = key;
    if (vars) { for (var k in vars) { val = val.split('{' + k + '}').join(vars[k]); } }
    return val;
}

function getLang() { return _currentLang; }

function setLang(code) {
    if (!I18N_LANGS[code]) code = 'en';
    _currentLang = code;
    try { localStorage.setItem('crushfactory_lang', code); } catch(e) {}
}

/* Auto-detect on load */
(function() {
    var saved = null;
    try { saved = localStorage.getItem('crushfactory_lang'); } catch(e) {}
    if (saved && I18N_LANGS[saved]) { _currentLang = saved; return; }
    var nav = (navigator.language || navigator.userLanguage || 'en').slice(0, 2).toLowerCase();
    if (I18N_LANGS[nav]) { _currentLang = nav; return; }
    _currentLang = 'en';
})();
